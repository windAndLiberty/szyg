export function getStageColor(stage: DealStage): string {
  const colors: Record<DealStage, string> = {
    [DealStage.InitialContact]: '#8B5CF6',
    [DealStage.NeedsConfirmed]: '#3B82F6',
    [DealStage.SolutionEval]: '#06B6D4',
    [DealStage.Negotiation]: '#F59E0B',
    [DealStage.Won]: '#10B981',
    [DealStage.Lost]: '#EF4444',
  }
  return colors[stage]
}

