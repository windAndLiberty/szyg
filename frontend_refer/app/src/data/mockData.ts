export function formatCurrency(value: number): string {
  if (value >= 1000000) {
    return `¥${(value / 1000000).toFixed(1)}M`
  }
  if (value >= 1000) {
    return `¥${(value / 1000).toFixed(0)}K`
  }
  return `¥${value}`
}

export function getDealsByStage(stage: DealStage): Deal[] {
  return deals.filter((d) => d.stage === stage)
}

export function getActiveDeals(): Deal[] {
  return deals.filter((d) => d.stage !== DealStage.Won && d.stage !== DealStage.Lost)
}

export function getTotalPipelineValue(): number {
  return getActiveDeals().reduce((sum, d) => sum + d.amount, 0)
}
