/**
 * AI 智能体库（预置，不支持用户自定义）
 *
 * 每个智能体 = 提示词（systemPrompt） + 是否启用业务工具（useTools）。
 * 大多数为纯提示词的轻量专家，少数（如文档助手）需要调用 szyg 业务工具。
 * 对话复用 /chat 界面：跳转 `/chat?agent={id}`，前端据此注入 system_prompt / use_tools。
 */

export interface AIAgent {
  id: string
  name: string
  desc: string
  category: string
  letter: string
  color: string // 头像渐变
  systemPrompt: string
  /** 是否启用 szyg 业务工具集（知识库/发布/调度等）。默认纯提示词。 */
  useTools?: boolean
  /** 需要简单 API/数据配置才能发挥全部能力（界面给出提示）。 */
  needsApi?: boolean
  /** 开场建议问题，渲染为快捷入口。 */
  suggestions: string[]
  isHot?: boolean
}

